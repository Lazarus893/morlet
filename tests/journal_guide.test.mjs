import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { JournalStore } from '../plugins/life-journal/store.mjs';
import { AgentHub } from '../plugins/agent-hub/store.mjs';
import { createFirstTaskFlow, firstTaskTool } from '../plugins/agent-hub/first-task.mjs';
import { materialWidgetKinds, availableWidgetKinds } from '../plugins/life-journal/widgets.mjs';
const scope = { account: 'local', userId: 'owner' };
function fixture(t) {
 const root = mkdtempSync(join(tmpdir(), 'guide-real-')), store = new JournalStore(root), hub = new AgentHub(root);
 const flow = createFirstTaskFlow({ hub });
 store.db.exec('CREATE TABLE journal_content_entries(id TEXT PRIMARY KEY,item_id TEXT NOT NULL,data TEXT NOT NULL)');
 const source = { id: 'a'.repeat(64), entryId: 'reading', source: 'github', title: '示例仓库的发布说明', hook: '新版本修复键盘操作', summary: '修复禁用按钮仍可由键盘触发的问题。', relevance: '可对照现有界面的键盘行为。', suggestion: '核对禁用按钮的鼠标与键盘行为。', topic: '界面交互', coverage: '已读发布说明，代码未核实', evidence: [{ quote: 'Disabled controls now ignore keyboard activation.', url: 'https://example.com/release' }], url: 'https://example.com/release', observedAt: Date.now(), exploration: false };
 source.itemId = store.mutate(scope, { operation: 'add', revision: 0, values: { title: '近期材料', source: { kind: 'automatic', channel: 'background', text: '授权资料' }, taskType: 'collection', taskData: { collection: { entries: [{ id: source.entryId, title: source.title, note: source.summary }] } } } }).items[0].id;
 const saveSource = () => store.db.prepare('INSERT OR REPLACE INTO journal_content_entries VALUES(?,?,?)').run(source.id, source.itemId, JSON.stringify(source)); saveSource();
 const snapshot = () => store.snapshot(scope);
 const choose = () => { const s = snapshot(), item = s.items.find(i => i.source.kind === 'guide'); return store.mutate(scope, { operation: 'widget', revision: s.revision, itemId: item.id, itemVersion: item.version, values: { kind: 'decision', action: 'choose', candidateId: source.id } }); };
 const follow = () => { const s = snapshot(), item = s.items.find(i => i.source.kind === 'guide'); return store.followGuide(scope, { itemId: item.id, itemVersion: item.version, revision: s.revision }); };
 t.after(() => { hub.close(); store.close(); rmSync(root, { recursive: true, force: true }); });
 return { root, store, hub, flow, source, saveSource, snapshot, choose, follow };
}
test('real guide selects evidenced recent material, persists choice, atomically creates one useful follow-up', t => {
 const f = fixture(t), before = f.snapshot().items[0];
 const first = f.store.ensureGuide(scope); assert.equal(first.guide.sources.length, 1);
 assert.equal(first.items.at(-1).steps.length, 0); assert.equal(first.items.at(-1).candidates[0].name, f.source.hook);
 assert.throws(f.follow, { code: 'GUIDE_CHOICE_REQUIRED' });
 f.choose(); assert.equal(f.store.ensureGuide(scope).items.at(-1).candidates[0].selected, true);
 const saved = f.follow(), item = saved.items.find(i => i.id === saved.guide.resultItemId);
 assert.ok(item.note.includes(f.source.evidence[0].quote)); assert.equal(item.steps[1].label, f.source.suggestion);
 assert.ok(item.steps.every(s => !s.done)); assert.equal(item.source.kind, 'user');
 assert.deepEqual(f.follow(), saved); assert.deepEqual(f.store.ensureGuide(scope), saved);
 assert.deepEqual(saved.items.find(i => i.id === before.id), before);
 assert.throws(f.choose, { code: 'GUIDE_ALREADY_STARTED' });
 const guide = f.snapshot().items.find(i => i.id === saved.guide.itemId);
 f.store.mutate(scope, { operation: 'done', revision: saved.revision, itemId: guide.id, itemVersion: guide.version });
 const archived = f.store.ensureGuide(scope).items.find(i => i.id === guide.id);
 assert.equal(archived.status, 'done');
 assert.deepEqual(materialWidgetKinds(archived), ['decision']); assert.deepEqual(availableWidgetKinds(archived), ['decision']);
 const reopened = new JournalStore(f.root); assert.equal(reopened.snapshot(scope).guide.resultItemId, item.id); reopened.close();
});
test('empty, foreign, stale and removed sources never produce invented recommendations', t => {
 const f = fixture(t);
 assert.equal(f.store.ensureGuide({ account: 'b'.repeat(64), userId: 'peer' }).guide.sources.length, 0);
 f.source.observedAt -= 20 * 86400000; f.saveSource(); assert.equal(f.store.ensureGuide(scope).guide.sources.length, 0);
 f.source.observedAt = Date.now(); f.saveSource(); f.store.ensureGuide(scope); f.choose();
 f.source.summary = '来源被更正'; f.saveSource(); assert.throws(f.follow, { code: 'GUIDE_SOURCE_CHANGED' });
 f.store.ensureGuide(scope); assert.equal(f.snapshot().guide.sources[0].summary, '来源被更正');
 f.store.db.prepare('DELETE FROM journal_content_entries').run(); assert.throws(f.follow, { code: 'GUIDE_SOURCE_CHANGED' });
 assert.equal(f.snapshot().guide.resultItemId, null);
});
test('deleting an unstarted guide allows a fresh introduction with the same sources', t => {
 const f = fixture(t), state = f.store.ensureGuide(scope), guide = state.items.find(i => i.id === state.guide.itemId);
 f.store.mutate(scope, { operation: 'delete', revision: state.revision, itemId: guide.id, itemVersion: guide.version });
 const restored = f.store.ensureGuide(scope);
 assert.notEqual(restored.guide.itemId, guide.id);
 assert.equal(restored.guide.sources.length, 1);
 assert.ok(restored.items.some(i => i.id === restored.guide.itemId));
});
test('guide uses an independent guarded run, preserves drafts, verifies reads, and resumes without duplicate dispatch', async t => {
 const f = fixture(t), pair = f.hub.pair({ label: 'Fixture Agent' }); f.hub.poll(pair.token, { runnerId: 'fixture', claim: false });
 const draft = f.flow.action({ operation: 'draft', text: '已有的个人草稿', requestId: 'draft' });
 f.store.ensureGuide(scope); f.choose(); const journal = f.follow();
 // Pairing alone does not configure a role. Set the existing runtime role through its stored config.
 const { writeFileSync, mkdirSync } = await import('node:fs');
 mkdirSync(join(f.root, '.runtime'), { recursive: true });
 writeFileSync(join(f.root, '.runtime/agent-hub.json'), JSON.stringify({ version: 1, agents: [], roles: { conversation: pair.endpointId } }), { mode: 0o600 });
 const first = f.flow.startGuide({ journal, requestId: 'start' });
 assert.deepEqual(f.flow.startGuide({ journal, requestId: 'repeat' }), first);
 assert.equal(f.hub.all('run').length, 1); assert.equal(f.flow.snapshot().flow.id, draft.flowId); assert.equal(f.flow.snapshot().flow.draft, '已有的个人草稿');
 const job = f.hub.poll(pair.token, { runnerId: 'fixture' }).job;
 await assert.rejects(firstTaskTool({ hub: f.hub, token: pair.token, input: { runId: job.id, lease: job.lease, callId: 'bad', arguments: { operation: 'propose', proposal: { title: '不允许', note: '不修改' } } } }), { code: 'FORBIDDEN' });
 f.hub.tool(pair.token, { tool: 'xiaoman_report', runId: job.id, lease: job.lease, callId: 'report', arguments: { summary: '已核对材料，下一步检查键盘操作。', outcome: 'completed' } });
 f.hub.event(pair.token, { runId: job.id, lease: job.lease, seq: f.hub.get('run', job.id).seq + 1, type: 'completed', value: '下一步检查禁用按钮。' });
 assert.equal(f.flow.guideSnapshot(journal).answer, null, 'a report without a current read is not success');
 f.flow.recordRead(f.hub.get('run', job.id), journal.items.find(i => i.id === journal.guide.resultItemId));
 assert.equal(f.flow.guideSnapshot(journal).answer, '下一步检查禁用按钮。');
 assert.deepEqual(f.flow.startGuide({ journal, requestId: 'again' }), first); assert.equal(f.hub.all('run').length, 1);
 const oldRun = structuredClone(f.hub.get('run', job.id)), oldMessages = f.hub.all('message'), beforeContinuation = f.snapshot();
 const conversationId = oldRun.conversationId;
 assert.equal(f.flow.guideSnapshot(journal).conversationId, conversationId);
 const input = { conversationId, content: '重新读取原始资料，只核对，不修改记录。', requestId: 'explicit-continuation', endpointId: pair.endpointId };
 const continuation = f.flow.continueGuide(input);
 assert.equal(continuation.run.conversationId, conversationId);
 assert.equal(continuation.run.firstTaskId, first.flowId); assert.equal(continuation.run.firstTaskMode, 'followup');
 assert.notEqual(continuation.run.id, oldRun.id);
 assert.deepEqual(f.flow.continueGuide(input), continuation, 'the same submitted message replays its receipt even while running');
 assert.throws(() => f.flow.continueGuide({ ...input, content: 'changed content' }), { code: 'CONFLICT' });
 assert.throws(() => f.flow.continueGuide({ ...input, requestId: 'concurrent-message' }), { code: 'FIRST_TASK_BUSY' });
 assert.equal(f.hub.all('run').length, 2);
 assert.equal(f.flow.guideSnapshot(journal).run.id, continuation.run.id);
 assert.equal(f.flow.guideSnapshot(journal).answer, null, 'the previous answer never masquerades as the new result');
 assert.equal(f.flow.snapshot().flow.id, draft.flowId); assert.equal(f.flow.snapshot().flow.draft, '已有的个人草稿');
 const resumed = f.hub.poll(pair.token, { runnerId: 'fixture' }).job;
 assert.equal(f.flow.context(resumed).savedItemId, journal.guide.resultItemId);
 assert.throws(() => f.flow.guardWrite(resumed, { operation: 'update', itemId: journal.guide.resultItemId, values: { note: 'unauthorized write' } }, {}), { code: 'FIRST_TASK_CONFIRM_REQUIRED' });
 f.hub.put('run', { ...f.hub.get('run', resumed.id), status: 'uncertain' });
 assert.throws(() => f.flow.continueGuide({ ...input, requestId: 'uncertain-message' }), { code: 'FIRST_TASK_RECOVERY_REQUIRED' });
 f.hub.put('run', { ...f.hub.get('run', resumed.id), status: 'running' });
 f.flow.recordRead(resumed, journal.items.find(i => i.id === journal.guide.resultItemId));
 f.hub.tool(pair.token, { tool: 'xiaoman_report', runId: resumed.id, lease: resumed.lease, callId: 'resumed-report', arguments: { summary: '重新核对后的结果。', outcome: 'completed' } });
 f.hub.event(pair.token, { runId: resumed.id, lease: resumed.lease, seq: f.hub.get('run', resumed.id).seq + 1, type: 'completed', value: '本轮重新核对：仍需实际测试键盘行为。' });
 const latest = f.flow.guideSnapshot(journal);
 assert.equal(latest.answer, '本轮重新核对：仍需实际测试键盘行为。');
 assert.equal(latest.run.id, resumed.id); assert.equal(latest.conversationId, conversationId);
 assert.deepEqual(f.hub.get('run', oldRun.id), oldRun);
 assert.ok(oldMessages.every(message => f.hub.all('message').some(current => current.id === message.id && current.text === message.text)));
 assert.deepEqual(f.snapshot(), beforeContinuation, 'continuing the guide never changes its item, material or journal history');
 assert.deepEqual(f.flow.continueGuide(input), continuation, 'a late retry does not start another run after completion');
 const ordinary = f.hub.newConversation({ endpointId: pair.endpointId });
 assert.equal(f.flow.continueGuide({ ...input, conversationId: ordinary.id, requestId: 'ordinary' }), null);
 assert.equal(f.hub.all('run').length, 2);
 const conversation = f.hub.conversation(conversationId);
 f.hub.put('conversation', { ...conversation, ownerId: 'another-owner' });
 assert.throws(() => f.flow.continueGuide({ ...input, requestId: 'foreign-owner' }), { code: 'FORBIDDEN' });
 f.hub.put('conversation', conversation);
 f.hub.bind({ channel: 'weixin', account: 'a'.repeat(64), peer: 'other', conversationId });
 assert.throws(() => f.flow.continueGuide({ ...input, requestId: 'bound-conversation' }), { code: 'FORBIDDEN' });
 assert.equal(f.hub.all('run').length, 2);
 assert.equal(f.hub.all('delivery').length, 0);
});
